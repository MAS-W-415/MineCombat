
"""Validate Minecraft Zombie YOLO annotations and split episodes."""

from __future__ import annotations

import json
import math
import random
from dataclasses import dataclass
from pathlib import Path


@dataclass(frozen=True)
class YoloBox:
    class_id: int
    center_x: float
    center_y: float
    width: float
    height: float

    def __post_init__(self) -> None:
        if self.class_id != 0:
            raise ValueError("Only class 0 (zombie) is supported")

        values = (
            self.center_x,
            self.center_y,
            self.width,
            self.height,
        )

        if not all(math.isfinite(v) for v in values):
            raise ValueError("YOLO coordinates must be finite")

        if self.width <= 0 or self.height <= 0:
            raise ValueError("Bounding-box dimensions must be positive")

        if (
            self.center_x - self.width / 2 < 0
            or self.center_x + self.width / 2 > 1
            or self.center_y - self.height / 2 < 0
            or self.center_y + self.height / 2 > 1
        ):
            raise ValueError("Bounding box exceeds image boundaries")


@dataclass(frozen=True)
class LabeledFrame:
    image_path: Path
    label_path: Path
    seed: int
    step: int
    boxes: tuple[YoloBox, ...]


def read_yolo_labels(path: str | Path) -> tuple[YoloBox, ...]:
    """Read YOLO boxes. An existing empty file is a negative sample."""

    path = Path(path)

    if not path.is_file():
        raise FileNotFoundError(
            f"Missing annotation: {path}. "
            "Use an empty .txt file only for verified negative frames."
        )

    boxes = []

    for line_number, line in enumerate(
        path.read_text(encoding="utf-8").splitlines(),
        start=1,
    ):
        line = line.strip()
        if not line:
            continue

        parts = line.split()
        if len(parts) != 5:
            raise ValueError(
                f"{path}:{line_number}: expected 5 YOLO fields"
            )

        try:
            box = YoloBox(
                class_id=int(parts[0]),
                center_x=float(parts[1]),
                center_y=float(parts[2]),
                width=float(parts[3]),
                height=float(parts[4]),
            )
        except ValueError as exc:
            raise ValueError(
                f"{path}:{line_number}: invalid YOLO annotation"
            ) from exc

        boxes.append(box)

    return tuple(boxes)


def load_labeled_frames(
    frames_dir: str | Path,
    labels_dir: str | Path,
) -> list[LabeledFrame]:
    """Match policy-frame manifest entries with human annotations."""

    frames_dir = Path(frames_dir)
    labels_dir = Path(labels_dir)

    manifest = frames_dir / "manifest.jsonl"

    if not manifest.is_file():
        raise FileNotFoundError(manifest)

    samples = []
    seen_images = set()

    for line_number, line in enumerate(
        manifest.read_text(encoding="utf-8").splitlines(),
        start=1,
    ):
        if not line.strip():
            continue

        record = json.loads(line)

        seed = record["seed"]
        step = record["step"]

        if (
            type(seed) is not int
            or type(step) is not int
            or seed < 0
            or step < 0
        ):
            raise ValueError(
                f"Invalid seed or step at manifest line {line_number}"
            )

        relative = Path(record["image"])

        # Accept only paths generated by PolicyFrameExporter.
        if (
            relative.is_absolute()
            or ".." in relative.parts
            or relative.parts != (
                f"seed_{seed:04d}",
                f"step_{step:05d}.png",
            )
        ):
            raise ValueError(
                f"Invalid image path at manifest line {line_number}"
            )

        image_path = frames_dir / relative
        label_path = labels_dir / relative.with_suffix(".txt")

        if image_path in seen_images:
            raise ValueError(f"Duplicate image: {image_path}")

        if not image_path.is_file():
            raise FileNotFoundError(image_path)

        boxes = read_yolo_labels(label_path)

        samples.append(
            LabeledFrame(
                image_path=image_path,
                label_path=label_path,
                seed=seed,
                step=step,
                boxes=boxes,
            )
        )

        seen_images.add(image_path)

    if not samples:
        raise ValueError("Dataset contains no labeled frames")

    return samples


def split_by_episode(
    samples: list[LabeledFrame],
    *,
    val_fraction: float = 0.2,
    random_seed: int = 42,
) -> tuple[list[LabeledFrame], list[LabeledFrame]]:
    """Split entire episodes, never individual adjacent frames."""

    if not math.isfinite(val_fraction) or not 0 < val_fraction < 1:
        raise ValueError("val_fraction must be between 0 and 1")

    episodes = sorted({sample.seed for sample in samples})

    if len(episodes) < 2:
        raise ValueError(
            "At least two episodes are required for a train/val split"
        )

    random.Random(random_seed).shuffle(episodes)

    num_val = max(
        1,
        min(
            len(episodes) - 1,
            math.ceil(len(episodes) * val_fraction),
        ),
    )

    val_seeds = set(episodes[:num_val])

    train = [
        sample for sample in samples
        if sample.seed not in val_seeds
    ]
    val = [
        sample for sample in samples
        if sample.seed in val_seeds
    ]

    return train, val
