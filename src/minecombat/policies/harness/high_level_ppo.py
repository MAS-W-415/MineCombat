
"""Semi-MDP GAE and PPO updates for high-level tactical decisions."""

from __future__ import annotations

from collections.abc import Sequence
from dataclasses import dataclass

import torch
from torch.distributions import Categorical

from .tactical_policy import HighLevelTacticalPolicy
from .tactical_rollout import TacticalTransition


@dataclass(frozen=True)
class HighLevelPPOConfig:
    gamma: float = 0.99
    gae_lambda: float = 0.95
    clip_ratio: float = 0.2
    value_coef: float = 0.5
    entropy_coef: float = 0.01
    update_epochs: int = 4
    max_grad_norm: float = 0.5

    def __post_init__(self):
        if not 0.0 <= self.gamma <= 1.0:
            raise ValueError("gamma must be in [0, 1]")
        if not 0.0 <= self.gae_lambda <= 1.0:
            raise ValueError("gae_lambda must be in [0, 1]")
        if not 0.0 < self.clip_ratio < 1.0:
            raise ValueError("clip_ratio must be in (0, 1)")
        if self.value_coef < 0 or self.entropy_coef < 0:
            raise ValueError("Loss coefficients must be non-negative")
        if self.update_epochs < 1 or self.max_grad_norm <= 0:
            raise ValueError("Invalid PPO optimization settings")


def compute_smdp_gae(
    transitions: Sequence[TacticalTransition],
    old_values: torch.Tensor,
    next_values: torch.Tensor,
    *,
    gamma: float,
    gae_lambda: float,
) -> tuple[torch.Tensor, torch.Tensor]:
    """Compute duration-aware advantages and value targets.

    Transitions must be in chronological order within an
    environment trajectory. Episode boundaries stop GAE recursion.

    Termination: no value bootstrap.
    Truncation: bootstrap, but do not cross into the next episode.
    """

    n = len(transitions)

    if n == 0:
        raise ValueError("No high-level transitions")

    if old_values.shape != (n,) or next_values.shape != (n,):
        raise ValueError("Value tensors must have shape [N]")

    if not 0.0 <= gamma <= 1.0:
        raise ValueError("gamma must be in [0, 1]")
    if not 0.0 <= gae_lambda <= 1.0:
        raise ValueError("gae_lambda must be in [0, 1]")

    old_values = old_values.detach()
    next_values = next_values.detach()

    advantages = torch.zeros_like(old_values)
    next_advantage = torch.zeros_like(old_values[0])

    for i in reversed(range(n)):
        transition = transitions[i]

        if transition.duration < 1:
            raise ValueError("Empty tactical transition")

        duration_discount = gamma ** transition.duration

        reward = transition.discounted_reward(gamma)

        # True termination cannot bootstrap.
        bootstrap_mask = 0.0 if transition.terminated else 1.0

        # Both termination and truncation stop trace propagation.
        continue_mask = (
            0.0
            if transition.terminated or transition.truncated
            else 1.0
        )

        delta = (
            reward
            + duration_discount
            * bootstrap_mask
            * next_values[i]
            - old_values[i]
        )

        # lambda is applied per high-level decision.
        advantage = (
            delta
            + duration_discount
            * gae_lambda
            * continue_mask
            * next_advantage
        )

        advantages[i] = advantage
        next_advantage = advantage

    returns = advantages + old_values
    return advantages, returns


def _stack_features(
    features,
    policy: HighLevelTacticalPolicy,
) -> torch.Tensor:
    """Convert recorded high-level states into a [N, D] batch."""

    vectors = [
        torch.as_tensor(
            feature,
            dtype=torch.float32,
            device=policy.device,
        ).detach()
        for feature in features
    ]

    for vector in vectors:
        if vector.shape != (policy.feature_dim,):
            raise ValueError(
                f"Expected features of shape ({policy.feature_dim},)"
            )

    return torch.stack(vectors, dim=0)


def update_high_level_ppo(
    policy: HighLevelTacticalPolicy,
    transitions: Sequence[TacticalTransition],
    optimizer: torch.optim.Optimizer,
    config: HighLevelPPOConfig,
) -> dict:
    """Run PPO updates using one collected high-level rollout.

    The rollout must have been generated by the behavior policy.
    Do not regenerate old action probabilities during optimization.
    """

    if not transitions:
        raise ValueError("Cannot update PPO with empty rollout")

    for transition in transitions:
        if (
            transition.behavior_log_prob is None
            or transition.behavior_value is None
        ):
            raise ValueError(
                "Missing behavior log probability or value"
            )

        if not 0 <= transition.tactic_id < policy.num_tactics:
            raise ValueError("Invalid recorded tactic ID")

    policy.train()

    # State vectors recorded at high-level decision boundaries.
    features = _stack_features(
        [t.features for t in transitions],
        policy,
    )

    next_features = _stack_features(
        [t.next_features for t in transitions],
        policy,
    )

    actions = torch.tensor(
        [t.tactic_id for t in transitions],
        dtype=torch.long,
        device=policy.device,
    )

    old_log_probs = torch.tensor(
        [t.behavior_log_prob for t in transitions],
        dtype=torch.float32,
        device=policy.device,
    )

    old_values = torch.tensor(
        [t.behavior_value for t in transitions],
        dtype=torch.float32,
        device=policy.device,
    )

    if (
        not torch.isfinite(old_log_probs).all()
        or not torch.isfinite(old_values).all()
    ):
        raise ValueError("Non-finite behavior statistics")

    # Freeze bootstrap estimates and targets before PPO epochs.
    with torch.no_grad():
        _, next_values = policy(next_features)

        advantages, returns = compute_smdp_gae(
            transitions,
            old_values,
            next_values,
            gamma=config.gamma,
            gae_lambda=config.gae_lambda,
        )

        if not torch.isfinite(advantages).all():
            raise ValueError("Non-finite advantages")

        # Normalize for policy optimization only.
        policy_advantages = advantages.clone()

        if len(transitions) > 1:
            policy_advantages = (
                policy_advantages - policy_advantages.mean()
            ) / (
                policy_advantages.std(unbiased=False) + 1e-8
            )

    metrics = {}

    for _ in range(config.update_epochs):
        logits, values = policy(features)

        distribution = Categorical(logits=logits)

        new_log_probs = distribution.log_prob(actions)

        ratio = torch.exp(new_log_probs - old_log_probs)

        unclipped = ratio * policy_advantages

        clipped = torch.clamp(
            ratio,
            1.0 - config.clip_ratio,
            1.0 + config.clip_ratio,
        ) * policy_advantages

        policy_loss = -torch.minimum(
            unclipped,
            clipped,
        ).mean()

        value_loss = 0.5 * (
            values - returns
        ).square().mean()

        entropy = distribution.entropy().mean()

        total_loss = (
            policy_loss
            + config.value_coef * value_loss
            - config.entropy_coef * entropy
        )

        optimizer.zero_grad(set_to_none=True)

        total_loss.backward()

        grad_norm = torch.nn.utils.clip_grad_norm_(
            policy.parameters(),
            max_norm=config.max_grad_norm,
        )

        optimizer.step()

        metrics = {
            "total_loss": float(total_loss.item()),
            "policy_loss": float(policy_loss.item()),
            "value_loss": float(value_loss.item()),
            "entropy": float(entropy.item()),
            "grad_norm": float(grad_norm.item()),
            "num_transitions": len(transitions),
        }

    return metrics
